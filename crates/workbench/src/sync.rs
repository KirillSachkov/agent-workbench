//! Derived pieces, regenerated idempotently from `.agents/skills`, the lock and the configuration:
//! Claude Code skill links, Codex `agents/openai.yaml`, OpenCode permission rules, the skill
//! registry and the managed block of `AGENTS.md`. Stale pieces are reported and regenerated; sync
//! never fails because of them.

use std::fmt;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result};
use serde_json::{Map, Value};

use crate::agents_md;
use crate::config::{Config, LinkMode};
use crate::files;
use crate::lock::Lock;
use crate::skills::{self, Skill};

const CLAUDE_LINK: &str = ".claude/skills";
const LINK_TARGET: &str = "../.agents/skills";
const REGISTRY: &str = ".agents/skills/REGISTRY.md";
const OPENCODE: &str = "opencode.json";
const CODEX_FILE: &str = "agents/openai.yaml";
const CODEX_HEADER: &str =
    "# Generated by workbench sync from disable-model-invocation in SKILL.md; do not edit.\n";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    Missing,
    Changed,
    Removed,
}

impl fmt::Display for Kind {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Kind::Missing => "missing",
            Kind::Changed => "out of date",
            Kind::Removed => "no longer needed",
        })
    }
}

#[derive(Default)]
pub struct Report {
    /// Derived files that were stale and got regenerated.
    pub stale: Vec<(String, Kind)>,
    pub warnings: Vec<String>,
}

impl Report {
    fn stale(&mut self, path: impl Into<String>, kind: Kind) {
        self.stale.push((path.into(), kind));
    }
}

pub fn run(project: &Path) -> Result<()> {
    let lock = Lock::load(project)?;
    if let Some(lock) = &lock {
        lock.guard()?;
    }
    let config = Config::load(project)?;
    let report = derive(project, lock.as_ref(), &config)?;
    if report.stale.is_empty() {
        println!("Derived files are up to date.");
    }
    for (path, kind) in &report.stale {
        println!("stale: {path} ({kind}); regenerated");
    }
    for warning in &report.warnings {
        eprintln!("warning: {warning}");
    }
    Ok(())
}

pub fn derive(project: &Path, lock: Option<&Lock>, config: &Config) -> Result<Report> {
    let mut report = Report::default();
    let skills = skills::scan(project)?;
    links(project, &skills, config.links, &mut report)?;
    codex(project, &skills, &mut report)?;
    opencode(project, &skills, lock, &mut report)?;
    ensure(project, REGISTRY, registry(&skills).as_bytes(), &mut report)?;
    managed_block(project, &skills, lock, &mut report)?;
    Ok(report)
}

/// Writes `content` at `path` unless it is already there; records it as stale otherwise.
fn ensure(project: &Path, path: &str, content: &[u8], report: &mut Report) -> Result<()> {
    let full = project.join(path);
    let kind = match files::read_optional(&full)? {
        Some(current) if current == content => return Ok(()),
        Some(_) => Kind::Changed,
        None => Kind::Missing,
    };
    files::write(&full, content)?;
    report.stale(path, kind);
    Ok(())
}

fn links(project: &Path, skills: &[Skill], mode: LinkMode, report: &mut Report) -> Result<()> {
    let link = project.join(CLAUDE_LINK);
    let meta = fs::symlink_metadata(&link).ok();
    match mode {
        LinkMode::Directory => match meta {
            Some(m) if m.file_type().is_symlink() => {
                if fs::read_link(&link)? != Path::new(LINK_TARGET) {
                    fs::remove_file(&link)?;
                    link_dir(&link, LINK_TARGET, report)?;
                    report.stale(CLAUDE_LINK, Kind::Changed);
                }
            }
            Some(m) if m.is_file() => {
                // A committed symlink checked out as a text stub (Windows without symlinks).
                fs::remove_file(&link)?;
                link_dir(&link, LINK_TARGET, report)?;
                report.warnings.push(format!(
                    "{CLAUDE_LINK} was a text file instead of a symlink (a checkout without \
                     symlink support); replaced it, do not commit the replacement"
                ));
                report.stale(CLAUDE_LINK, Kind::Changed);
            }
            Some(_) => report.warnings.push(format!(
                "{CLAUDE_LINK} is a directory; left as is. Set links.claude = \"per-skill\" in \
                 workbench.toml to keep Claude-only skills there"
            )),
            None => {
                link_dir(&link, LINK_TARGET, report)?;
                report.stale(CLAUDE_LINK, Kind::Missing);
            }
        },
        LinkMode::PerSkill => {
            if meta.is_some_and(|m| !m.is_dir()) {
                fs::remove_file(&link)?;
            }
            fs::create_dir_all(&link)?;
            for skill in skills {
                let path = format!("{CLAUDE_LINK}/{}", skill.name);
                let target = format!("../../.agents/skills/{}", skill.name);
                let entry = project.join(&path);
                match fs::read_link(&entry) {
                    Ok(current) if current == Path::new(&target) => {}
                    Ok(_) => {
                        fs::remove_file(&entry)?;
                        link_dir(&entry, &target, report)?;
                        report.stale(path, Kind::Changed);
                    }
                    Err(_) if entry.exists() => {} // the project's own Claude-only skill
                    Err(_) => {
                        link_dir(&entry, &target, report)?;
                        report.stale(path, Kind::Missing);
                    }
                }
            }
            // Links to skills that are gone.
            for entry in fs::read_dir(&link)? {
                let entry = entry?.path();
                if let Ok(target) = fs::read_link(&entry)
                    && target.starts_with("../../.agents/skills")
                    && !entry.exists()
                {
                    fs::remove_file(&entry)?;
                    let name = entry.file_name().unwrap_or_default().to_string_lossy();
                    report.stale(format!("{CLAUDE_LINK}/{name}"), Kind::Removed);
                }
            }
        }
    }
    Ok(())
}

#[cfg(unix)]
fn link_dir(link: &Path, target: &str, _report: &mut Report) -> Result<()> {
    if let Some(parent) = link.parent() {
        fs::create_dir_all(parent)?;
    }
    std::os::unix::fs::symlink(target, link).with_context(|| format!("link {}", link.display()))
}

/// Best effort on Windows: a symlink when allowed, else a junction, else a local copy.
#[cfg(windows)]
fn link_dir(link: &Path, target: &str, report: &mut Report) -> Result<()> {
    if let Some(parent) = link.parent() {
        fs::create_dir_all(parent)?;
    }
    if std::os::windows::fs::symlink_dir(target, link).is_ok() {
        return Ok(());
    }
    let absolute = link.parent().unwrap_or(link).join(target);
    let junction = std::process::Command::new("cmd")
        .args(["/C", "mklink", "/J"])
        .arg(link)
        .arg(&absolute)
        .output();
    if junction.is_ok_and(|o| o.status.success()) {
        report.warnings.push(format!(
            "created a junction at {} instead of a symlink",
            link.display()
        ));
        return Ok(());
    }
    copy_dir(&absolute, link)?;
    report.warnings.push(format!(
        "copied skills into {} because links are unavailable; this local copy must not be \
         committed and goes stale until the next sync",
        link.display()
    ));
    Ok(())
}

#[cfg(windows)]
fn copy_dir(from: &Path, to: &Path) -> Result<()> {
    fs::create_dir_all(to)?;
    for entry in fs::read_dir(from)? {
        let entry = entry?;
        let target = to.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            copy_dir(&entry.path(), &target)?;
        } else {
            fs::copy(entry.path(), target)?;
        }
    }
    Ok(())
}

/// Codex reads the invocation policy only from `agents/openai.yaml` next to `SKILL.md`. A file
/// the skill ships itself (without our header) is left alone.
fn codex(project: &Path, skills: &[Skill], report: &mut Report) -> Result<()> {
    let content = format!("{CODEX_HEADER}policy:\n  allow_implicit_invocation: false\n");
    for skill in skills {
        let path = format!("{}/{}/{CODEX_FILE}", skills::DIR, skill.name);
        let current = files::read_optional(&project.join(&path))?;
        let ours = current
            .as_deref()
            .is_none_or(|c| c.starts_with(CODEX_HEADER.as_bytes()));
        if !ours {
            continue;
        }
        if skill.user_invoked {
            ensure(project, &path, content.as_bytes(), report)?;
        } else if current.is_some() {
            files::remove_and_prune(&project.join(&path), &project.join(skills::DIR))?;
            report.stale(path, Kind::Removed);
        }
    }
    Ok(())
}

/// OpenCode expresses user-only skills as `deny` rules on its skill tool. Rules are merged into the
/// project's own `opencode.json`; everything else in it is kept. A rule is removed only for a
/// harness skill whose frontmatter no longer makes it user-invoked.
fn opencode(
    project: &Path,
    skills: &[Skill],
    lock: Option<&Lock>,
    report: &mut Report,
) -> Result<()> {
    let path = project.join(OPENCODE);
    let current = files::read_optional(&path)?;
    let user: Vec<&Skill> = skills.iter().filter(|s| s.user_invoked).collect();
    if current.is_none() {
        if project.join("opencode.jsonc").exists() && !user.is_empty() {
            report.warnings.push(format!(
                "opencode.jsonc is not edited by workbench; add \"deny\" rules under \
                 permission.skill for: {}",
                user.iter()
                    .map(|s| s.name.as_str())
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
            return Ok(());
        }
        if user.is_empty() {
            return Ok(());
        }
    }

    let mut root: Value = match &current {
        Some(bytes) => match serde_json::from_slice(bytes) {
            Ok(value) => value,
            Err(e) => {
                report.warnings.push(format!(
                    "{OPENCODE} is not plain JSON ({e}); its skill permissions were not updated"
                ));
                return Ok(());
            }
        },
        None => serde_json::json!({ "$schema": "https://opencode.ai/config.json" }),
    };
    let Some(object) = root.as_object_mut() else {
        report
            .warnings
            .push(format!("{OPENCODE} is not a JSON object; left as is"));
        return Ok(());
    };
    let before = Value::Object(object.clone());

    let permission = object
        .entry("permission")
        .or_insert_with(|| Value::Object(Map::new()));
    if let Value::String(all) = permission {
        // `"permission": "ask"` applies to every tool; keep that meaning for the rest.
        *permission = serde_json::json!({ "*": all.clone() });
    }
    let Some(permission) = permission.as_object_mut() else {
        report.warnings.push(format!(
            "{OPENCODE}: permission is not an object; left as is"
        ));
        return Ok(());
    };
    let rules = permission
        .entry("skill")
        .or_insert_with(|| Value::Object(Map::new()));
    if let Value::String(all) = rules {
        *rules = serde_json::json!({ "*": all.clone() });
    }
    let Some(rules) = rules.as_object_mut() else {
        report.warnings.push(format!(
            "{OPENCODE}: permission.skill is not an object; left as is"
        ));
        return Ok(());
    };
    for skill in &user {
        rules.insert(skill.name.clone(), Value::String("deny".into()));
    }
    for skill in skills.iter().filter(|s| !s.user_invoked) {
        let harness_skill = lock.is_some_and(|l| l.skills.contains_key(&skill.name));
        if harness_skill && rules.get(&skill.name).and_then(Value::as_str) == Some("deny") {
            rules.remove(&skill.name);
        }
    }

    if Value::Object(object.clone()) == before && current.is_some() {
        return Ok(());
    }
    let mut text = serde_json::to_string_pretty(&root)?;
    text.push('\n');
    files::write(&path, text.as_bytes())?;
    let kind = if current.is_some() {
        Kind::Changed
    } else {
        Kind::Missing
    };
    report.stale(OPENCODE, kind);
    Ok(())
}

fn registry(skills: &[Skill]) -> String {
    let mut out = String::from(
        "<!-- Generated by workbench sync from SKILL.md frontmatter; do not edit. -->\n\n\
         # Skill registry\n\n\
         An index of the skills in this directory. The source of truth is each `SKILL.md`. \
         User-invoked skills start only when the user calls them by name; model-invoked skills \
         may also be started by the agent.\n\n\
         | Skill | Invocation | Description |\n|---|---|---|\n",
    );
    for skill in skills {
        let invocation = if skill.user_invoked { "user" } else { "model" };
        let description = skill.description.replace('|', "\\|").replace('\n', " ");
        out.push_str(&format!(
            "| {} | {invocation} | {description} |\n",
            skill.name
        ));
    }
    out
}

fn managed_block(
    project: &Path,
    skills: &[Skill],
    lock: Option<&Lock>,
    report: &mut Report,
) -> Result<()> {
    let path = project.join(agents_md::FILE);
    let Some(bytes) = files::read_optional(&path)? else {
        report.warnings.push(format!(
            "{} is missing, so the managed block was not written",
            agents_md::FILE
        ));
        return Ok(());
    };
    let text =
        String::from_utf8(bytes).with_context(|| format!("{} is not UTF-8", agents_md::FILE))?;
    let updated = agents_md::with_block(&text, &agents_md::block(skills, lock));
    if updated != text {
        files::write(&path, updated.as_bytes())?;
        let kind = if text.contains("<!-- BEGIN workbench managed block") {
            Kind::Changed
        } else {
            Kind::Missing
        };
        report.stale(format!("{} (managed block)", agents_md::FILE), kind);
    }
    Ok(())
}
